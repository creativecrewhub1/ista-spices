export const productRevenue = products
  .map((product) => {
    const avgPrice =
      product.packSizes.reduce((sum, p) => sum + p.price, 0) / product.packSizes.length
    const unitsSold = product.unitsPackedThisBatch * 6
    return {
      id: product.id,
      name: product.name,
      revenue: Math.round(unitsSold * avgPrice * 0.4),
      unitsSold,
    }
  })
  .sort((a, b) => a.revenue - b.revenue)

const weekdayLabels = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun']
// Relative shape of a week's demand — mirrors the overall weeklyRevenue curve
// (mid-week dip, weekend peak on Saturday) so each product's line looks plausible.
const weekdayShape = [0.78, 0.88, 0.84, 0.94, 1.08, 1.34, 1.14]

export const productWeeklyTrends: Record<string, RevenuePoint[]> = Object.fromEntries(
  productRevenue.map((product) => {
    const weeklySlice = product.revenue / 4
    return [
      product.id,
      weekdayLabels.map((label, i) => ({
        label,
        revenue: Math.round((weeklySlice * weekdayShape[i]) / 7),
      })),
    ]
  }),
)

